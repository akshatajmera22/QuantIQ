# ============================================================
# GEMINI CALL
# ============================================================

def _call_gemini(
    prompt: str
):
    """
    Make exactly one Gemini SDK request.

    SDK-level retries are disabled in the client configuration.
    """

    response = client.models.generate_content(
        model=MODEL,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json"
        ),
    )

    # Preserve QuantIQ token tracking.
    record_usage(
        response=response,
        call_type="planner"
    )

    return response


# ============================================================
# CREATE PLAN
# ============================================================

def create_plan(
    question: str,
    schema_context: str,
    conversation_context: str = "",
    max_retries: int = MAX_RETRIES,
) -> Dict[str, Any]:
    """
    Create a structured analysis plan using Gemini.

    Retry behavior:

        max_retries = 0
            -> 1 total Gemini request

        max_retries = 1
            -> maximum 2 total Gemini requests

    Only transient Gemini/service errors are retried.
    """

    question = clean_string(question)

    if not question:
        raise ValueError(
            "Question cannot be empty."
        )

    if not schema_context or not schema_context.strip():
        raise ValueError(
            "Schema context cannot be empty."
        )

    prompt = build_planner_prompt(
        question=question,
        schema_context=schema_context,
        conversation_context=conversation_context,
    )

    # Prevent accidental negative values.
    try:
        max_retries = max(0, int(max_retries))
    except (TypeError, ValueError):
        max_retries = MAX_RETRIES

    total_attempts = max_retries + 1

    last_error: Optional[Exception] = None

    for attempt in range(total_attempts):

        try:

            response = _call_gemini(prompt)

            response_text = getattr(
                response,
                "text",
                None
            )

            if not response_text:
                raise ValueError(
                    "Gemini returned no text."
                )

            raw_plan = extract_json(
                response_text
            )

            normalized_plan = normalize_plan(
                raw_plan,
                schema_context,
            )

            return normalized_plan

        except ValueError:
            # Planner validation errors and invalid JSON are
            # not transient Gemini service errors.
            #
            # Retrying the exact same invalid response does not
            # solve the underlying planning problem.
            raise

        except Exception as error:

            last_error = error

            transient = is_transient_error(
                error
            )

            retries_remaining = (
                attempt < max_retries
            )

            if not transient or not retries_remaining:

                raise RuntimeError(
                    "Gemini planner failed after "
                    f"{attempt + 1} total attempt(s): "
                    f"{error}"
                ) from error

            # ------------------------------------------------
            # Exponential backoff + jitter
            # ------------------------------------------------

            delay = (
                RETRY_DELAY_SECONDS
                * (2 ** attempt)
            )

            jitter = random.uniform(
                0,
                0.75
            )

            total_delay = (
                delay + jitter
            )

            print(
                "[Gemini Planner] "
                f"Transient error detected "
                f"(attempt {attempt + 1}/{total_attempts}): "
                f"{error}"
            )

            print(
                "[Gemini Planner] "
                f"Retrying once after "
                f"{total_delay:.2f}s..."
            )

            time.sleep(
                total_delay
            )

    # This should not normally be reached.
    raise RuntimeError(
        "Gemini planner failed."
        + (
            f" Last error: {last_error}"
            if last_error
            else ""
        )
    )


