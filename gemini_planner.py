# ============================================================
# TRANSIENT ERROR DETECTION
# ============================================================

def is_transient_error(error: Exception) -> bool:
    """
    Return True only for errors where retrying may reasonably help.

    Retry:
        408
        429
        500
        502
        503
        504
        RESOURCE_EXHAUSTED
        UNAVAILABLE
        INTERNAL
        DEADLINE_EXCEEDED

    Do NOT retry:
        400
        401
        403
        invalid API key
        malformed request
        invalid JSON generated by the model
        schema/planner validation problems
        other permanent client-side errors
    """

    error_text = str(error).upper()

    transient_markers = [
        "408",
        "429",
        "500",
        "502",
        "503",
        "504",
        "RESOURCE_EXHAUSTED",
        "UNAVAILABLE",
        "INTERNAL",
        "DEADLINE_EXCEEDED",
        "TIMEOUT",
        "TIMED OUT",
    ]

    return any(marker in error_text for marker in transient_markers)


# ============================================================
# JSON EXTRACTION
# ============================================================

def extract_json(text: str) -> Dict[str, Any]:
    """
    Extract a JSON object from Gemini's response.

    Handles:
    - pure JSON
    - ```json ... ```
    - accidental surrounding text
    """

    if not text:
        raise ValueError("Gemini returned an empty response.")

    cleaned = text.strip()

    # Remove markdown fences.
    cleaned = re.sub(
        r"^```(?:json)?\s*",
        "",
        cleaned,
        flags=re.IGNORECASE
    )

    cleaned = re.sub(
        r"\s*```$",
        "",
        cleaned
    )

    cleaned = cleaned.strip()

    # First try direct parsing.
    try:
        parsed = json.loads(cleaned)

        if not isinstance(parsed, dict):
            raise ValueError(
                "Gemini returned JSON, but the root value is not an object."
            )

        return parsed

    except json.JSONDecodeError:
        pass

    # Try finding the first JSON object inside surrounding text.
    start = cleaned.find("{")

    if start == -1:
        raise ValueError(
            "Could not find a JSON object in Gemini's response."
        )

    decoder = json.JSONDecoder()

    try:
        parsed, _ = decoder.raw_decode(cleaned[start:])
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Gemini returned invalid JSON: {exc}"
        ) from exc

    if not isinstance(parsed, dict):
        raise ValueError(
            "Gemini returned JSON, but the root value is not an object."
        )

    return parsed


# ============================================================
# GENERIC HELPERS
# ============================================================

def ensure_list(value: Any) -> List[Any]:
    """
    Convert None/single values into a list.
    """

    if value is None:
        return []

    if isinstance(value, list):
        return value

    return [value]


def clean_string(value: Any) -> str:
    if value is None:
        return ""

    return str(value).strip()


def normalize_identifier(value: Any) -> str:
    """
    Normalize SQL identifiers for comparison only.

    This does NOT change the identifier returned to the SQL generator.
    """

    text = clean_string(value)

    text = text.strip()

    if text.startswith("`") and text.endswith("`"):
        text = text[1:-1]

    if text.startswith('"') and text.endswith('"'):
        text = text[1:-1]

    if text.startswith("[") and text.endswith("]"):
        text = text[1:-1]

    return text.strip().lower()


def normalize_column_reference(value: Any) -> str:
    """
    Normalize table.column style references.
    """

    text = clean_string(value)

    text = text.replace("`", "")
    text = text.replace('"', "")
    text = text.replace("[", "")
    text = text.replace("]", "")

    return text.strip().lower()


# ============================================================
# SCHEMA RELATIONSHIP EXTRACTION
# ============================================================

def extract_schema_relationships(schema_context: str) -> List[Dict[str, str]]:
    """
    Extract FK relationships from the schema context.

    Expected schema lines can look like:

        - "inventory"."film_id" -> "film"."film_id"

    or:

        - inventory.film_id -> film.film_id

    This is only used to validate Gemini's proposed joins.
    """

    relationships: List[Dict[str, str]] = []

    if not schema_context:
        return relationships

    lines = schema_context.splitlines()

    for line in lines:
        if "->" not in line:
            continue

        left, right = line.split("->", 1)

        left = normalize_column_reference(left)
        right = normalize_column_reference(right)

        # Remove prefixes such as:
        # FOREIGN KEY RELATIONSHIPS:
        # -
        left = left.lstrip("- ").strip()
        right = right.lstrip("- ").strip()

        if "." not in left or "." not in right:
            continue

        relationships.append(
            {
                "left": left,
                "right": right
            }
        )

    return relationships


def relationship_exists(
    left_table: str,
    left_column: str,
    right_table: str,
    right_column: str,
    relationships: List[Dict[str, str]]
) -> bool:
    """
    Check whether a proposed join exists in the discovered schema.

    The direction is treated as irrelevant because:

        A.x -> B.x

    and

        B.x -> A.x

    represent the same relationship.
    """

    proposed_left = (
        f"{normalize_identifier(left_table)}."
        f"{normalize_identifier(left_column)}"
    )

    proposed_right = (
        f"{normalize_identifier(right_table)}."
        f"{normalize_identifier(right_column)}"
    )

    for relationship in relationships:
        schema_left = relationship["left"]
        schema_right = relationship["right"]

        if (
            proposed_left == schema_left
            and proposed_right == schema_right
        ):
            return True

        if (
            proposed_left == schema_right
            and proposed_right == schema_left
        ):
            return True

    return False


# ============================================================
# JOIN NORMALIZATION
# ============================================================

def normalize_joins(
    joins: Any,
    schema_context: str
) -> List[Dict[str, str]]:
    """
    Normalize and validate Gemini's JOIN definitions.

    Invalid/invented relationships are rejected instead of silently
    allowing Gemini to invent database relationships.
    """

    relationships = extract_schema_relationships(schema_context)

    normalized: List[Dict[str, str]] = []

    for join in ensure_list(joins):

        if not isinstance(join, dict):
            continue

        left_table = clean_string(
            join.get("left_table")
        )

        left_column = clean_string(
            join.get("left_column")
        )

        right_table = clean_string(
            join.get("right_table")
        )

        right_column = clean_string(
            join.get("right_column")
        )

        if not all(
            [
                left_table,
                left_column,
                right_table,
                right_column,
            ]
        ):
            continue

        # If FK relationships were found, only accept joins
        # represented in the discovered schema.
        if relationships:

            if not relationship_exists(
                left_table,
                left_column,
                right_table,
                right_column,
                relationships,
            ):
                raise ValueError(
                    "Gemini proposed a JOIN that does not exist "
                    f"in the discovered schema: "
                    f"{left_table}.{left_column} = "
                    f"{right_table}.{right_column}"
                )

        normalized.append(
            {
                "left_table": left_table,
                "left_column": left_column,
                "right_table": right_table,
                "right_column": right_column,
            }
        )

    return normalized


# ============================================================
# ANALYSIS NORMALIZATION
# ============================================================

def normalize_filters(filters: Any) -> List[Dict[str, Any]]:
    """
    Normalize filters without hardcoding dataset-specific fields.
    """

    normalized = []

    for item in ensure_list(filters):

        if not isinstance(item, dict):
            continue

        column = clean_string(
            item.get("column")
        )

        operator = clean_string(
            item.get("operator")
        ).upper()

        value = item.get("value")

        if not column or not operator:
            continue

        normalized.append(
            {
                "column": column,
                "operator": operator,
                "value": value,
            }
        )

    return normalized


def normalize_sort(sort: Any) -> List[Dict[str, str]]:
    """
    Normalize sorting definitions.
    """

    normalized = []

    for item in ensure_list(sort):

        if not isinstance(item, dict):
            continue

        column = clean_string(
            item.get("column")
        )

        direction = clean_string(
            item.get("direction", "DESC")
        ).upper()

        if not column:
            continue

        if direction not in {"ASC", "DESC"}:
            direction = "DESC"

        normalized.append(
            {
                "column": column,
                "direction": direction,
            }
        )

    return normalized


def normalize_output_columns(value: Any) -> List[str]:
    """
    Normalize columns that should appear in ordinary row/list queries.

    This is intentionally generic. Nothing is hardcoded.
    """

    result = []

    for item in ensure_list(value):

        if isinstance(item, str):
            column = item.strip()

        elif isinstance(item, dict):
            column = clean_string(
                item.get("column")
                or item.get("name")
            )

        else:
            continue

        if column:
            result.append(column)

    return result


def normalize_analysis(
    analysis: Dict[str, Any],
    schema_context: str
) -> Dict[str, Any]:
    """
    Normalize one analysis object while preserving the planner's
    dynamic structure.
    """

    result: Dict[str, Any] = {}

    # --------------------------------------------------------
    # Intent
    # --------------------------------------------------------

    result["intent"] = clean_string(
        analysis.get("intent")
    )

    # --------------------------------------------------------
    # Metric
    # --------------------------------------------------------

    metric = analysis.get("metric")

    if metric is None:
        result["metric"] = None
    else:
        result["metric"] = clean_string(metric)

    # --------------------------------------------------------
    # Dimension
    # --------------------------------------------------------

    dimension = analysis.get("dimension")

    if dimension is None:
        result["dimension"] = None
    else:
        result["dimension"] = clean_string(dimension)

    # --------------------------------------------------------
    # Aggregation
    # --------------------------------------------------------

    aggregation = clean_string(
        analysis.get("aggregation")
    ).upper()

    if not aggregation:
        aggregation = "NONE"

    result["aggregation"] = aggregation

    # --------------------------------------------------------
    # Tables
    # --------------------------------------------------------

    tables = []

    for table in ensure_list(
        analysis.get("tables")
    ):

        table_name = clean_string(table)

        if table_name:
            tables.append(table_name)

    result["tables"] = tables

    # --------------------------------------------------------
    # Joins
    # --------------------------------------------------------

    result["joins"] = normalize_joins(
        analysis.get("joins", []),
        schema_context,
    )

    # --------------------------------------------------------
    # Filters
    # --------------------------------------------------------

    result["filters"] = normalize_filters(
        analysis.get("filters", [])
    )

    # --------------------------------------------------------
    # Output columns
    # --------------------------------------------------------

    result["output_columns"] = normalize_output_columns(
        analysis.get("output_columns", [])
    )

    # --------------------------------------------------------
    # Group by
    # --------------------------------------------------------

    group_by = []

    for column in ensure_list(
        analysis.get("group_by")
    ):

        column_name = clean_string(column)

        if column_name:
            group_by.append(column_name)

    result["group_by"] = group_by

    # --------------------------------------------------------
    # Sort
    # --------------------------------------------------------

    result["sort"] = normalize_sort(
        analysis.get("sort", [])
    )

    # --------------------------------------------------------
    # Limit
    # --------------------------------------------------------

    limit = analysis.get("limit")

    if limit is None:
        result["limit"] = None

    else:
        try:
            result["limit"] = int(limit)
        except (ValueError, TypeError):
            result["limit"] = None

    # --------------------------------------------------------
    # Having
    # --------------------------------------------------------

    result["having"] = normalize_filters(
        analysis.get("having", [])
    )

    # --------------------------------------------------------
    # Ranking
    # --------------------------------------------------------

    ranking = analysis.get("ranking")

    if isinstance(ranking, dict):

        result["ranking"] = {
            "enabled": bool(
                ranking.get("enabled", False)
            ),
            "column": clean_string(
                ranking.get("column")
            ),
            "direction": clean_string(
                ranking.get(
                    "direction",
                    "DESC"
                )
            ).upper(),
        }

    else:
        result["ranking"] = {
            "enabled": False,
            "column": "",
            "direction": "DESC",
        }

    # --------------------------------------------------------
    # Keep additional planner metadata
    # --------------------------------------------------------

    for key in [
        "question",
        "description",
        "comparison",
        "time_grain",
        "date_column",
        "value",
    ]:

        if key in analysis:
            result[key] = analysis[key]

    return result


# ============================================================
# PLAN NORMALIZATION
# ============================================================

def normalize_plan(
    plan: Dict[str, Any],
    schema_context: str
) -> Dict[str, Any]:
    """
    Normalize the entire Gemini planner response.
    """

    if not isinstance(plan, dict):
        raise ValueError(
            "Gemini planner response must be a JSON object."
        )

    normalized: Dict[str, Any] = {}

    # --------------------------------------------------------
    # Main question
    # --------------------------------------------------------

    normalized["question"] = clean_string(
        plan.get("question")
    )

    # --------------------------------------------------------
    # Intent
    # --------------------------------------------------------

    normalized["intent"] = clean_string(
        plan.get("intent")
    )

    # --------------------------------------------------------
    # Tables
    # --------------------------------------------------------

    tables = []

    for table in ensure_list(
        plan.get("tables")
    ):

        table_name = clean_string(table)

        if table_name:
            tables.append(table_name)

    normalized["tables"] = tables

    # --------------------------------------------------------
    # Global joins
    # --------------------------------------------------------

    normalized["joins"] = normalize_joins(
        plan.get("joins", []),
        schema_context,
    )

    # --------------------------------------------------------
    # Analyses
    # --------------------------------------------------------

    raw_analyses = plan.get("analyses")

    if raw_analyses is None:

        # Support a single-analysis planner response.
        raw_analyses = [plan]

    elif isinstance(raw_analyses, dict):

        raw_analyses = [raw_analyses]

    elif not isinstance(raw_analyses, list):

        raise ValueError(
            "Planner field 'analyses' must be an array."
        )

    analyses = []

    for raw_analysis in raw_analyses:

        if not isinstance(raw_analysis, dict):
            continue

        analysis = normalize_analysis(
            raw_analysis,
            schema_context,
        )

        analyses.append(analysis)

    if not analyses:
        raise ValueError(
            "Gemini planner returned no usable analyses."
        )

    normalized["analyses"] = analyses

    # --------------------------------------------------------
    # Optional planner metadata
    # --------------------------------------------------------

    if "reasoning" in plan:
        normalized["reasoning"] = clean_string(
            plan.get("reasoning")
        )

    if "notes" in plan:
        normalized["notes"] = clean_string(
            plan.get("notes")
        )

    return normalized


